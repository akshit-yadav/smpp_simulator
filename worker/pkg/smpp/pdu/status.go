func (s Status) String() string {
	if n, ok := StatusNames[s]; ok {
		return n
	}
	if s.IsVendor() {
		return fmt.Sprintf("VENDOR(0x%03X)", uint32(s))
	}
	return fmt.Sprintf("0x%08X", uint32(s))
}

// IsVendor reports whether s is in the admin-definable vendor range 0x400-0x4FF.
func (s Status) IsVendor() bool { return s >= VendorStatusMin && s <= VendorStatusMax }
